async function main() {
  console.log(`Seeding ${DEITIES.length} deities into database...`);
  for (const d of DEITIES) {
    const upserted = await prisma.deity.upsert({
      where: { slug: d.slug },
      update: {
        name: d.name,
        teluguName: d.teluguName,
        tamilName: d.tamilName,
        kannadaName: d.kannadaName,
        hindiName: d.hindiName,
        category: d.category,
        isFeatured: d.isFeatured,
        orderIndex: d.orderIndex,
        imageName: d.imageName,
        imageUrl: d.imageUrl,
        aliases: d.aliases,
        description: d.description,
        isActive: d.isActive,
      },
      create: {
        slug: d.slug,
        name: d.name,
        teluguName: d.teluguName,
        tamilName: d.tamilName,
        kannadaName: d.kannadaName,
        hindiName: d.hindiName,
        category: d.category,
        isFeatured: d.isFeatured,
        orderIndex: d.orderIndex,
        imageName: d.imageName,
        imageUrl: d.imageUrl,
        aliases: d.aliases,
        description: d.description,
        isActive: d.isActive,
      },
    });
    console.log(`✓ Seeded deity: ${upserted.name} (${upserted.slug}) [Featured: ${upserted.isFeatured}]`);
  }
  console.log('Deity seeding completed successfully!');
}

main()
  .catch((e) => {
    console.error('Error seeding deities:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
